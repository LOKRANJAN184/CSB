// Copies the version from package.json into public/js/version.js so the web
// app knows its own version. Runs automatically before every build/release.
const fs = require('fs');
const path = require('path');
const { version } = require('../package.json');
const out = path.join(__dirname, '../public/js/version.js');
fs.writeFileSync(out, `// Generated by scripts/sync-version.js — do not edit by hand.\nexport const APP_VERSION = '${version}';\n`);
console.log(`version.js → ${version}`);
